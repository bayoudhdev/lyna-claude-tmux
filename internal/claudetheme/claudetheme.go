const (
	// Generator is the value of the generator field in every generated file.
	Generator = "lyna-tmux"
	// DirName is the theme directory inside Claude Code's config directory and
	// inside a plugin.
	DirName = "themes"
	// MaxFileBytes is the size above which Claude Code skips a theme file.
	MaxFileBytes = 256 << 10
	// filePrefix starts every generated file name.
	filePrefix = "lyna-"
	// checksumPrefix names the digest algorithm inside the checksum field.
	checksumPrefix = "sha256:"
)

var (
	// ErrNotGenerated reports an existing theme file that lyna-tmux did not
	// write or that was changed since; Write leaves it alone.
	ErrNotGenerated = errors.New("claudetheme: existing theme file was not generated by lyna-tmux or was edited")
	// ErrPaletteName reports a palette name that cannot form a theme file name.
	ErrPaletteName = errors.New("claudetheme: palette name must be lowercase letters, digits and hyphens")
)

