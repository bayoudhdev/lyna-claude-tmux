// Package claudetheme turns the workspace palettes into Claude Code custom
// themes, so the agent's own interface matches the tmux status line, borders
// and pickers around it.
//
// Claude Code loads custom themes from JSON files in <config dir>/themes and
// from the themes/ directory of installed plugins. A file holds an optional
// display name, a built-in base preset and a sparse map of color token
// overrides; unknown top-level fields, unknown tokens and invalid color values
// are ignored by Claude Code, and its /theme editor saves only name, base and
// overrides back.
//
// Generated files carry two extra top-level fields, generator and checksum,
// which identify an untouched lyna-tmux file. Write replaces a theme file only
// when both still match, so a theme the user wrote, or edited by hand or in the
// /theme editor, is never overwritten.
package claudetheme

